assert(!tail.includes("action_system_move.png"),"never repeat the move action icon across grid");
assert(tail.includes("t-cell.move:focus-visible"),"keyboard-accessible movement feedback");
assert(battle.includes('className="t-cell move"'),"existing movement tap buttons preserved");
assert(battle.includes("HudPortrait"),"selected unit receives a stable portrait component");
assert(battle.includes('key={unit.id} unit={unit}'),"portrait retries on unit switch");
